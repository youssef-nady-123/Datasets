-- Task 31: Find employees who earn more than the average salary of
-- their own department (correlated subquery).
SELECT e1.EmployeeID, e1.FirstName, e1.LastName, e1.Department, e1.Salary
FROM Sales.Employees e1
WHERE e1.Salary > (
    SELECT AVG(e2.Salary) FROM Sales.Employees e2 WHERE e2.Department = e1.Department
);
GO

-- Task 32: Find each customer's largest single order using a correlated
-- subquery (instead of window functions).
SELECT o1.OrderID, o1.CustomerID, o1.Sales
FROM Sales.Orders o1
WHERE o1.Sales = (
    SELECT MAX(o2.Sales) FROM Sales.Orders o2 WHERE o2.CustomerID = o1.CustomerID
);
GO

-- Task 33: Find products whose price is higher than the average price of
-- all OTHER products in the same category (correlated, excludes itself).
SELECT p1.ProductID, p1.Product, p1.Category, p1.Price
FROM Sales.Products p1
WHERE p1.Price > (
    SELECT AVG(p2.Price)
    FROM Sales.Products p2
    WHERE p2.Category = p1.Category AND p2.ProductID <> p1.ProductID
);
GO

-- Task 34: Nested subquery - find customers who spent more than the
-- average total spend across all customers (subquery inside subquery).
SELECT CustomerID, TotalSpend
FROM (
    SELECT CustomerID, SUM(Sales) AS TotalSpend
    FROM Sales.Orders
    GROUP BY CustomerID
) spend
WHERE TotalSpend > (
    SELECT AVG(TotalSpend)
    FROM (
        SELECT SUM(Sales) AS TotalSpend
        FROM Sales.Orders
        GROUP BY CustomerID
    ) avg_sub
);
GO

-- Task 35: Find salespeople whose every order has Sales greater than 100
-- (correlated NOT EXISTS pattern - "for all" condition).
SELECT DISTINCT e.EmployeeID, e.FirstName, e.LastName
FROM Sales.Employees e
WHERE EXISTS (SELECT 1 FROM Sales.Orders o WHERE o.SalesPersonID = e.EmployeeID)
  AND NOT EXISTS (
      SELECT 1 FROM Sales.Orders o
      WHERE o.SalesPersonID = e.EmployeeID AND o.Sales <= 100
  );
GO

-- Task 36: Find the second most expensive product in each category using
-- a correlated subquery (no window functions).
SELECT p1.ProductID, p1.Product, p1.Category, p1.Price
FROM Sales.Products p1
WHERE 1 = (
    SELECT COUNT(*)
    FROM Sales.Products p2
    WHERE p2.Category = p1.Category AND p2.Price > p1.Price
);
GO



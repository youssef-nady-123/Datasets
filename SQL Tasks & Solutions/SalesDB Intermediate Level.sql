-- Task 17: Use a CTE to find customers whose total spend places them in
-- the top 10% of all customers by spend.
WITH CustomerSpend AS (
    SELECT CustomerID, SUM(Sales) AS TotalSpend
    FROM Sales.Orders
    GROUP BY CustomerID
),
RankedSpend AS (
    SELECT CustomerID, TotalSpend,
           PERCENT_RANK() OVER (ORDER BY TotalSpend DESC) AS PctRank
    FROM CustomerSpend
)
SELECT CustomerID, TotalSpend
FROM RankedSpend
WHERE PctRank <= 0.10;
GO

-- Task 18: Use a CTE to compute each employee's tenure category based on
-- BirthDate-derived age band, then count employees per band.
WITH AgeBands AS (
    SELECT EmployeeID,
           CASE
               WHEN DATEDIFF(YEAR, BirthDate, GETDATE()) < 35 THEN 'Under 35'
               WHEN DATEDIFF(YEAR, BirthDate, GETDATE()) BETWEEN 35 AND 50 THEN '35-50'
               ELSE 'Over 50'
           END AS AgeBand
    FROM Sales.Employees
)
SELECT AgeBand, COUNT(*) AS EmployeeCount
FROM AgeBands
GROUP BY AgeBand;
GO

-- Task 19: Recursive CTE - trace the full chain of managers above a
-- specific employee (e.g., EmployeeID = 25) up to the top.
WITH ManagerChain AS (
    SELECT EmployeeID, FirstName, LastName, ManagerID, 0 AS ChainLevel
    FROM Sales.Employees
    WHERE EmployeeID = 25
    UNION ALL
    SELECT e.EmployeeID, e.FirstName, e.LastName, e.ManagerID, mc.ChainLevel + 1
    FROM Sales.Employees e
    INNER JOIN ManagerChain mc ON e.EmployeeID = mc.ManagerID
)
SELECT EmployeeID, FirstName, LastName, ManagerID, ChainLevel
FROM ManagerChain
ORDER BY ChainLevel;
GO

-- Task 20: Use two chained CTEs to find, for each category, the customer
-- who spent the most in that category.
WITH CategorySpend AS (
    SELECT o.CustomerID, p.Category, SUM(o.Sales) AS Spend
    FROM Sales.Orders o
    INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
    GROUP BY o.CustomerID, p.Category
),
RankedCategorySpend AS (
    SELECT *, RANK() OVER (PARTITION BY Category ORDER BY Spend DESC) AS rnk
    FROM CategorySpend
)
SELECT Category, CustomerID, Spend
FROM RankedCategorySpend
WHERE rnk = 1;
GO

-- Task 21: CTE to identify customers with an increasing spend trend
-- across their last 3 orders (each order's Sales higher than the previous).
WITH Last3 AS (
    SELECT OrderID, CustomerID, OrderDate, Sales,
           ROW_NUMBER() OVER (PARTITION BY CustomerID ORDER BY OrderDate DESC) AS rn
    FROM Sales.Orders
),
Ordered3 AS (
    SELECT OrderID, CustomerID, OrderDate, Sales, rn,
           LAG(Sales) OVER (PARTITION BY CustomerID ORDER BY OrderDate) AS PrevSales
    FROM Last3
    WHERE rn <= 3
)
SELECT DISTINCT CustomerID
FROM Ordered3 o1
WHERE NOT EXISTS (
    SELECT 1 FROM Ordered3 o2
    WHERE o2.CustomerID = o1.CustomerID AND o2.PrevSales IS NOT NULL AND o2.Sales <= o2.PrevSales
);
GO

-- Task 22: CTE-based data mart: total sales, order count, and average
-- order value per year and category in one query.
WITH YearlyCategorySales AS (
    SELECT YEAR(o.OrderDate) AS OrderYear, p.Category,
           COUNT(*) AS OrderCount, SUM(o.Sales) AS TotalSales
    FROM Sales.Orders o
    INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
    GROUP BY YEAR(o.OrderDate), p.Category
)
SELECT OrderYear, Category, OrderCount, TotalSales,
       TotalSales / NULLIF(OrderCount, 0) AS AvgOrderValue
FROM YearlyCategorySales
ORDER BY OrderYear, TotalSales DESC;
GO

-- Task 23: Recursive CTE - generate a sequence of the last 6 calendar
-- months (as year-month labels) ending at the most recent OrderDate.
WITH MonthSeries AS (
    SELECT CAST(DATEFROMPARTS(YEAR(MaxDate), MONTH(MaxDate), 1) AS DATE) AS MonthStart, 0 AS Step
    FROM (SELECT MAX(OrderDate) AS MaxDate FROM Sales.Orders) m
    UNION ALL
    SELECT DATEADD(MONTH, -1, MonthStart), Step + 1
    FROM MonthSeries
    WHERE Step < 5
)
SELECT FORMAT(MonthStart, 'yyyy-MM') AS YearMonth
FROM MonthSeries
ORDER BY MonthStart;
GO

-- Task 24: CTE to find pairs of customers from the same country who have
-- an identical Score (self-join within a CTE).
WITH ScoredCustomers AS (
    SELECT CustomerID, FirstName, LastName, Country, Score
    FROM Sales.Customers
)
SELECT a.CustomerID AS CustomerA, b.CustomerID AS CustomerB, a.Country, a.Score
FROM ScoredCustomers a
INNER JOIN ScoredCustomers b
    ON a.Country = b.Country AND a.Score = b.Score AND a.CustomerID < b.CustomerID;
GO



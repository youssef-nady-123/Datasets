-- Task 1: For each product category, find total revenue, total quantity
-- sold, and number of distinct customers who bought from it.
SELECT p.Category,
       SUM(o.Sales) AS TotalRevenue,
       SUM(o.Quantity) AS TotalQuantity,
       COUNT(DISTINCT o.CustomerID) AS DistinctCustomers
FROM Sales.Orders o
INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
GROUP BY p.Category
ORDER BY TotalRevenue DESC;
GO

-- Task 2: For each salesperson, find their department (via Employees),
-- total orders handled, and total revenue generated.
SELECT e.EmployeeID, e.FirstName + ' ' + e.LastName AS SalesPerson,
       e.Department, COUNT(o.OrderID) AS OrderCount, SUM(o.Sales) AS TotalRevenue
FROM Sales.Employees e
INNER JOIN Sales.Orders o ON e.EmployeeID = o.SalesPersonID
GROUP BY e.EmployeeID, e.FirstName, e.LastName, e.Department
ORDER BY TotalRevenue DESC;
GO

-- Task 3: Find the top-selling product (by total Sales revenue) per
-- Category using aggregation joined to Products.
SELECT p.Category, p.Product, SUM(o.Sales) AS TotalSales
FROM Sales.Orders o
INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
GROUP BY p.Category, p.Product
HAVING SUM(o.Sales) = (
    SELECT MAX(CategoryProductTotal)
    FROM (
        SELECT p2.Category, p2.Product, SUM(o2.Sales) AS CategoryProductTotal
        FROM Sales.Orders o2
        INNER JOIN Sales.Products p2 ON o2.ProductID = p2.ProductID
        WHERE p2.Category = p.Category
        GROUP BY p2.Category, p2.Product
    ) sub
    WHERE sub.Category = p.Category
);
GO

-- Task 4: For each country, find the total revenue generated by
-- customers from that country and the number of orders placed.
SELECT c.Country, COUNT(o.OrderID) AS OrderCount, SUM(o.Sales) AS TotalRevenue
FROM Sales.Customers c
INNER JOIN Sales.Orders o ON c.CustomerID = o.CustomerID
GROUP BY c.Country
ORDER BY TotalRevenue DESC;
GO

-- Task 5: Find each manager's total team revenue - sum of Sales generated
-- by all employees who report directly to them.
SELECT m.EmployeeID AS ManagerID, m.FirstName + ' ' + m.LastName AS Manager,
       SUM(o.Sales) AS TeamRevenue
FROM Sales.Employees m
INNER JOIN Sales.Employees e ON e.ManagerID = m.EmployeeID
INNER JOIN Sales.Orders o ON o.SalesPersonID = e.EmployeeID
GROUP BY m.EmployeeID, m.FirstName, m.LastName
ORDER BY TeamRevenue DESC;
GO

-- Task 6: List customers who bought products from more than 3 different
-- categories (join + distinct count + having).
SELECT c.CustomerID, c.FirstName, c.LastName,
       COUNT(DISTINCT p.Category) AS CategoriesPurchased
FROM Sales.Customers c
INNER JOIN Sales.Orders o ON c.CustomerID = o.CustomerID
INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
GROUP BY c.CustomerID, c.FirstName, c.LastName
HAVING COUNT(DISTINCT p.Category) > 3;
GO

-- Task 7: Find the average order value per gender of salesperson
-- (join Orders to Employees).
SELECT e.Gender, COUNT(o.OrderID) AS OrderCount, AVG(o.Sales) AS AvgOrderValue
FROM Sales.Orders o
INNER JOIN Sales.Employees e ON o.SalesPersonID = e.EmployeeID
GROUP BY e.Gender;
GO

-- Task 8: For each customer, find how many different salespeople
-- have served them.
SELECT c.CustomerID, c.FirstName, c.LastName,
       COUNT(DISTINCT o.SalesPersonID) AS DistinctSalespeople
FROM Sales.Customers c
INNER JOIN Sales.Orders o ON c.CustomerID = o.CustomerID
GROUP BY c.CustomerID, c.FirstName, c.LastName
ORDER BY DistinctSalespeople DESC;
GO



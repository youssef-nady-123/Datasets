-- Task 47: Load top 10 customers by total spend into a temp table,
-- then join it back to Customers for full details.
IF OBJECT_ID('tempdb..#TopCustomers') IS NOT NULL DROP TABLE #TopCustomers;

SELECT TOP 10 CustomerID, SUM(Sales) AS TotalSpend
INTO #TopCustomers
FROM Sales.Orders
GROUP BY CustomerID
ORDER BY TotalSpend DESC;

SELECT c.CustomerID, c.FirstName, c.LastName, c.Country, t.TotalSpend
FROM #TopCustomers t
INNER JOIN Sales.Customers c ON t.CustomerID = c.CustomerID
ORDER BY t.TotalSpend DESC;

DROP TABLE #TopCustomers;
GO

-- Task 48: Use a table variable to stage monthly sales totals, then
-- calculate month-over-month growth from it.
DECLARE @MonthlySales TABLE (OrderMonth VARCHAR(7), TotalSales INT);

INSERT INTO @MonthlySales (OrderMonth, TotalSales)
SELECT FORMAT(OrderDate, 'yyyy-MM'), SUM(Sales)
FROM Sales.Orders
GROUP BY FORMAT(OrderDate, 'yyyy-MM');

SELECT OrderMonth, TotalSales,
       TotalSales - LAG(TotalSales) OVER (ORDER BY OrderMonth) AS MonthOverMonthChange
FROM @MonthlySales
ORDER BY OrderMonth;
GO

-- Task 49: Create a stored procedure that returns all orders for a given
-- CustomerID, then execute it.
CREATE OR ALTER PROCEDURE Sales.usp_GetCustomerOrders
    @CustomerID INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT o.OrderID, o.OrderDate, o.OrderStatus, o.Sales, p.Product
    FROM Sales.Orders o
    INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
    WHERE o.CustomerID = @CustomerID
    ORDER BY o.OrderDate;
END;
GO

EXEC Sales.usp_GetCustomerOrders @CustomerID = 5;
GO

-- Task 50: Create a stored procedure that returns top N salespeople by
-- revenue, with N as a parameter, then execute it for the top 5.
CREATE OR ALTER PROCEDURE Sales.usp_TopSalespeople
    @TopN INT = 5
AS
BEGIN
    SET NOCOUNT ON;
    SELECT TOP (@TopN) e.EmployeeID, e.FirstName + ' ' + e.LastName AS SalesPerson,
           SUM(o.Sales) AS TotalRevenue
    FROM Sales.Orders o
    INNER JOIN Sales.Employees e ON o.SalesPersonID = e.EmployeeID
    GROUP BY e.EmployeeID, e.FirstName, e.LastName
    ORDER BY TotalRevenue DESC;
END;
GO

EXEC Sales.usp_TopSalespeople @TopN = 5;
GO


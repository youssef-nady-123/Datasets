-- Task 37: Build a formatted order label like 'ORD-000123 | 2024-08-12'
-- combining string formatting and date formatting.
SELECT OrderID,
       'ORD-' + RIGHT('000000' + CAST(OrderID AS VARCHAR(10)), 6)
       + ' | ' + FORMAT(OrderDate, 'yyyy-MM-dd') AS OrderLabel
FROM Sales.Orders;
GO

-- Task 38: For each customer, build a summary string:
-- "FirstName LastName - N orders since <first order date>".
SELECT c.CustomerID,
       c.FirstName + ' ' + c.LastName + ' - '
       + CAST(COUNT(o.OrderID) AS VARCHAR(10)) + ' orders since '
       + FORMAT(MIN(o.OrderDate), 'MMM yyyy') AS CustomerSummary
FROM Sales.Customers c
INNER JOIN Sales.Orders o ON c.CustomerID = o.CustomerID
GROUP BY c.CustomerID, c.FirstName, c.LastName;
GO

-- Task 39: Extract the weekday name for each order and pivot-style count
-- orders per weekday using conditional aggregation.
SELECT DATENAME(WEEKDAY, OrderDate) AS WeekdayName, COUNT(*) AS OrderCount
FROM Sales.Orders
GROUP BY DATENAME(WEEKDAY, OrderDate), DATEPART(WEEKDAY, OrderDate)
ORDER BY DATEPART(WEEKDAY, OrderDate);
GO

-- Task 40: Build employee "badge codes" using initials + zero-padded
-- EmployeeID + hire-decade derived from BirthDate (e.g., "JH-0001-70s").
SELECT EmployeeID,
       LEFT(FirstName, 1) + LEFT(LastName, 1) + '-'
       + RIGHT('0000' + CAST(EmployeeID AS VARCHAR(10)), 4) + '-'
       + CAST((YEAR(BirthDate) / 10) * 10 AS VARCHAR(4)) + 's' AS BadgeCode
FROM Sales.Employees;
GO

-- Task 41: Find orders placed in the last quarter of any year
-- (Oct-Dec) and format the order date as 'Q4 <year>'.
SELECT OrderID, OrderDate, 'Q4 ' + CAST(YEAR(OrderDate) AS VARCHAR(4)) AS Quarter
FROM Sales.Orders
WHERE MONTH(OrderDate) IN (10, 11, 12);
GO

-- Task 42: Standardize and combine ShipAddress and BillAddress into a

-- Task 25: Use PIVOT to show total Sales per Category as columns,
-- one row per OrderYear.
SELECT OrderYear, Accessories, Clothing, Electronics, Home, Sports
FROM (
    SELECT YEAR(o.OrderDate) AS OrderYear, p.Category, o.Sales
    FROM Sales.Orders o
    INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
) src
PIVOT (
    SUM(Sales) FOR Category IN ([Accessories], [Clothing], [Electronics], [Home], [Sports])
) piv
ORDER BY OrderYear;
GO

-- Task 26: Use PIVOT to show employee count per Department as columns,
-- split by Gender.
SELECT Gender, Sales, Marketing, IT, Finance, HR, Operations
FROM (
    SELECT Gender, Department, EmployeeID
    FROM Sales.Employees
) src
PIVOT (
    COUNT(EmployeeID) FOR Department IN ([Sales], [Marketing], [IT], [Finance], [HR], [Operations])
) piv;
GO

-- Task 27: Conditional aggregation (without PIVOT) showing order counts
-- per OrderStatus per year.
SELECT YEAR(OrderDate) AS OrderYear,
       SUM(CASE WHEN OrderStatus = 'Delivered' THEN 1 ELSE 0 END) AS Delivered,
       SUM(CASE WHEN OrderStatus = 'Shipped' THEN 1 ELSE 0 END) AS Shipped,
       SUM(CASE WHEN OrderStatus = 'Processing' THEN 1 ELSE 0 END) AS Processing,
       SUM(CASE WHEN OrderStatus = 'Cancelled' THEN 1 ELSE 0 END) AS Cancelled
FROM Sales.Orders
GROUP BY YEAR(OrderDate)
ORDER BY OrderYear;
GO

-- Task 28: UNPIVOT-style query: turn per-category summary columns back
-- into rows (build the summary first with conditional aggregation,
-- then unpivot).
WITH CategoryTotals AS (
    SELECT
        SUM(CASE WHEN p.Category = 'Accessories' THEN o.Sales ELSE 0 END) AS Accessories,
        SUM(CASE WHEN p.Category = 'Clothing' THEN o.Sales ELSE 0 END) AS Clothing,
        SUM(CASE WHEN p.Category = 'Electronics' THEN o.Sales ELSE 0 END) AS Electronics,
        SUM(CASE WHEN p.Category = 'Home' THEN o.Sales ELSE 0 END) AS Home,
        SUM(CASE WHEN p.Category = 'Sports' THEN o.Sales ELSE 0 END) AS Sports
    FROM Sales.Orders o
    INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
)
SELECT Category, TotalSales
FROM CategoryTotals
UNPIVOT (TotalSales FOR Category IN (Accessories, Clothing, Electronics, Home, Sports)) up;
GO

-- Task 29: Show total salary cost per department as columns, pivoted by
-- Gender, using PIVOT.
SELECT Department, M AS MaleSalaryCost, F AS FemaleSalaryCost
FROM (
    SELECT Department, Gender, Salary FROM Sales.Employees
) src
PIVOT (
    SUM(Salary) FOR Gender IN ([M], [F])
) piv;
GO

-- Task 30: Conditional aggregation showing, per SalesPersonID, the count
-- of small (<300), medium (300-900), and large (>900) orders.
SELECT SalesPersonID,
       SUM(CASE WHEN Sales < 300 THEN 1 ELSE 0 END) AS SmallOrders,
       SUM(CASE WHEN Sales BETWEEN 300 AND 900 THEN 1 ELSE 0 END) AS MediumOrders,
       SUM(CASE WHEN Sales > 900 THEN 1 ELSE 0 END) AS LargeOrders
FROM Sales.Orders
GROUP BY SalesPersonID
ORDER BY SalesPersonID;
GO



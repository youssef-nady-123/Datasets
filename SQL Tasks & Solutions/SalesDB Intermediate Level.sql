-- Task 9: For each order, show the cumulative count of orders placed by
-- that customer up to and including that order.
SELECT OrderID, CustomerID, OrderDate,
       COUNT(*) OVER (PARTITION BY CustomerID ORDER BY OrderDate, OrderID
                       ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS OrdersSoFar
FROM Sales.Orders;
GO

-- Task 10: Rank salespeople by total revenue and show only the top 3
-- overall using a window function + filter.
WITH SalesTotals AS (
    SELECT SalesPersonID, SUM(Sales) AS TotalSales,
           DENSE_RANK() OVER (ORDER BY SUM(Sales) DESC) AS RevenueRank
    FROM Sales.Orders
    GROUP BY SalesPersonID
)
SELECT SalesPersonID, TotalSales, RevenueRank
FROM SalesTotals
WHERE RevenueRank <= 3;
GO

-- Task 11: For each customer's orders, calculate the percentage change in
-- Sales compared to their immediately preceding order.
SELECT OrderID, CustomerID, OrderDate, Sales,
       LAG(Sales) OVER (PARTITION BY CustomerID ORDER BY OrderDate) AS PrevSales,
       CASE WHEN LAG(Sales) OVER (PARTITION BY CustomerID ORDER BY OrderDate) IS NULL THEN NULL
            ELSE CAST(Sales - LAG(Sales) OVER (PARTITION BY CustomerID ORDER BY OrderDate) AS FLOAT)
                 / NULLIF(LAG(Sales) OVER (PARTITION BY CustomerID ORDER BY OrderDate), 0) * 100
       END AS PctChange
FROM Sales.Orders;
GO

-- Task 12: Find the median Sales value using PERCENTILE_CONT.
SELECT DISTINCT
    PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY Sales) OVER () AS MedianSales
FROM Sales.Orders;
GO

-- Task 13: For each department, show every employee's salary alongside
-- the department's average, and flag if they earn above or below it.
SELECT EmployeeID, FirstName, LastName, Department, Salary,
       AVG(Salary) OVER (PARTITION BY Department) AS DeptAvgSalary,
       CASE WHEN Salary > AVG(Salary) OVER (PARTITION BY Department)
            THEN 'Above Average' ELSE 'Below Average' END AS SalaryFlag
FROM Sales.Employees;
GO

-- Task 14: Compute the cumulative distribution (CUME_DIST) of employee
-- salaries to see what percentile each employee falls into.
SELECT EmployeeID, FirstName, LastName, Salary,
       CUME_DIST() OVER (ORDER BY Salary) AS SalaryPercentile
FROM Sales.Employees;
GO

-- Task 15: For each product, show its price rank within its category and
-- the price gap to the next cheaper product in the same category.
SELECT ProductID, Product, Category, Price,
       RANK() OVER (PARTITION BY Category ORDER BY Price DESC) AS PriceRank,
       Price - LEAD(Price) OVER (PARTITION BY Category ORDER BY Price DESC) AS GapToNextCheaper
FROM Sales.Products;
GO

-- Task 16: Identify, per SalesPersonID, the order with the LARGEST drop
-- in Sales compared to the previous order (biggest negative swing).
WITH OrderChanges AS (
    SELECT OrderID, SalesPersonID, OrderDate, Sales,
           Sales - LAG(Sales) OVER (PARTITION BY SalesPersonID ORDER BY OrderDate) AS SalesChange
    FROM Sales.Orders
),
RankedDrops AS (
    SELECT *, RANK() OVER (PARTITION BY SalesPersonID ORDER BY SalesChange ASC) AS DropRank
    FROM OrderChanges
    WHERE SalesChange IS NOT NULL
)
SELECT OrderID, SalesPersonID, OrderDate, Sales, SalesChange
FROM RankedDrops
WHERE DropRank = 1
ORDER BY SalesChange ASC;
GO



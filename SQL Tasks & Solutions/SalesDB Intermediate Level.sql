-- Task 43: Find orders where Sales doesn't match Quantity * unit Price
-- from the Products table (potential data entry error).
SELECT o.OrderID, o.ProductID, o.Quantity, p.Price,
       o.Quantity * p.Price AS ExpectedSales, o.Sales AS ActualSales
FROM Sales.Orders o
INNER JOIN Sales.Products p ON o.ProductID = p.ProductID
WHERE o.Sales <> o.Quantity * p.Price;
GO

-- Task 44: Find duplicate customers - same FirstName, LastName, and
-- Country appearing more than once.
SELECT FirstName, LastName, Country, COUNT(*) AS DuplicateCount
FROM Sales.Customers
GROUP BY FirstName, LastName, Country
HAVING COUNT(*) > 1;
GO

-- Task 45: Find orders referencing a CustomerID, ProductID, or
-- SalesPersonID that doesn't exist in the respective reference table
-- (referential integrity check).
SELECT o.OrderID, 'Invalid CustomerID' AS Issue
FROM Sales.Orders o
LEFT JOIN Sales.Customers c ON o.CustomerID = c.CustomerID
WHERE c.CustomerID IS NULL
UNION ALL
SELECT o.OrderID, 'Invalid ProductID'
FROM Sales.Orders o
LEFT JOIN Sales.Products p ON o.ProductID = p.ProductID
WHERE p.ProductID IS NULL
UNION ALL
SELECT o.OrderID, 'Invalid SalesPersonID'
FROM Sales.Orders o
LEFT JOIN Sales.Employees e ON o.SalesPersonID = e.EmployeeID
WHERE e.EmployeeID IS NULL;
GO

-- Task 46: Flag orders where ShipDate is earlier than OrderDate
-- (logically impossible - data quality issue).
SELECT OrderID, OrderDate, ShipDate
FROM Sales.Orders
WHERE ShipDate < OrderDate;
GO


